/**
 * Belirli bir kategoriden rastgele n adet benzersiz seçenek seçer.
 * Son gösterilen seçenekleri hafızada tutarak üst üste aynı seçeneklerin gelmesini engeller.
 */
class PoolRandomizer {
  constructor() {
    this.history = {
      olay: new Set(),
      kisiler: new Set(),
      mekan: new Set(),
      zaman: new Set()
    };
  }

  getRandomOptions(category, count = 4) {
    const pool = STORY_POOLS[category];
    if (!pool) return [];

    let available = pool.filter(item => !this.history[category].has(item));

    // Eğer havuzdaki kullanılabilir eleman sayısı count'tan azsa geçmişi sıfırla
    if (available.length < count) {
      this.history[category].clear();
      available = [...pool];
    }

    // Karıştır (Fisher-Yates Shuffle)
    const shuffled = [...available].sort(() => 0.5 - Math.random());
    const selected = shuffled.slice(0, count);

    // Seçilenleri hafızaya ekle
    selected.forEach(item => this.history[category].add(item));

    return selected;
  }

  resetHistory() {
    Object.keys(this.history).forEach(cat => this.history[cat].clear());
  }
}

export const poolRandomizer = new PoolRandomizer();
